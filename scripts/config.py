"""Small non-executing configuration format shared by setup/start/doctor."""
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / '.env.local'

def load(path=CONFIG):
    values = {}
    if not path.exists(): return values
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith('#'): continue
        name, sep, raw = line.partition('=')
        if not sep or not re.fullmatch(r'[A-Z][A-Z0-9_]*', name):
            raise ValueError('Invalid configuration line; use KEY=value')
        value = json.loads(raw) if raw.startswith('"') else raw
        if not isinstance(value, str) or '\n' in value or '\r' in value:
            raise ValueError('Configuration values must be single-line strings')
        values[name] = value
    return values

def save(values, path=CONFIG):
    # No shell sourcing, secret echoing, or world-readable intermediate file.
    payload = '# Generated by scripts/setup.py; do not commit.\n' + ''.join(
        name + '=' + json.dumps(value) + '\n' for name, value in sorted(values.items()))
    temp = path.with_name(path.name + '.tmp')
    fd = os.open(temp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.chmod(temp, 0o600)
    with os.fdopen(fd, 'w') as stream: stream.write(payload)
    os.replace(temp, path)
